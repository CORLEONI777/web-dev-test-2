export function getBookBySlug(slug: string): Book | undefined {
  return BOOKS.find((b) => b.slug === slug);
}

export function getBooksByGenre(genre: string): Book[] {
  return BOOKS.filter((b) => b.genres.includes(genre));
}

export function getBooksByAuthor(authorSlug: string): Book[] {
  return BOOKS.filter((b) => b.authorSlug === authorSlug);
}

export function getPublicDomainBooks(): Book[] {
  return BOOKS.filter((b) => b.isPublicDomain);
}

export function getTrendingBooks(): Book[] {
  return BOOKS.filter((b) => b.trending);
}

export function getFeaturedBook(): Book {
  return BOOKS.find((b) => b.featured) ?? BOOKS[0];
}

export function searchBooks(query: string): Book[] {
  const q = query.toLowerCase();
  return BOOKS.filter(
    (b) =>
      b.title.toLowerCase().includes(q) ||
      b.author.toLowerCase().includes(q) ||
      b.genres.some((g) => g.toLowerCase().includes(q)) ||
      b.tags.some((t) => t.toLowerCase().includes(q))
  );
}
